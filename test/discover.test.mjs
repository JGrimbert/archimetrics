const made = []
after(() => { for (const d of made) rmSync(d, { recursive: true, force: true }) })

/** Un projet écrit dans un dossier temporaire (hors de `test/`, que `node --test` parcourt). */
function project(files) {
  const root = mkdtempSync(join(tmpdir(), 'archimetrics-test-decouverte-'))
  made.push(root)
  for (const [rel, body] of Object.entries(files)) {
    mkdirSync(join(root, rel, '..'), { recursive: true })
    writeFileSync(join(root, rel), body)
  }
  return root
}

const load = (root) => {
  const cfg = loadConfig(root)
  cfg.useGit = false
  return cfg
}

// Un monorepo sans `archimetrics.config.json` : workspaces à motif, alias Vite et tsconfig, service Python, code généré.
const MONOREPO = {
  'package.json': JSON.stringify({ name: 'mono', private: true, workspaces: ['apps/*', 'packages/**', '!packages/ignore'], scripts: { outil: 'node scripts/outil.mjs --vite' } }),
  'apps/web/package.json': JSON.stringify({ name: '@m/web', dependencies: { vue: '3' } }),
  'apps/web/index.html': '<html><script type="module" src="/src/main.js"></script><script src="https://cdn.x/y.js"></script></html>',
  'apps/web/vite.config.js': "import { fileURLToPath } from 'url'\nexport default {\n  resolve: {\n    // l'alias de src\n    alias: { '@': fileURLToPath(new URL('./src', import.meta.url)), '~lib': path.resolve(__dirname, 'lib') },\n  },\n}\n",
  'apps/web/src/main.js': "import { b } from '@/b.js'\nimport { c } from '@m/commun'\nexport const m = b + c\n",
  'apps/web/src/b.js': 'export const b = 1\n',
  'apps/web/src/gen/types.js': '// @generated by outil\nexport const T = 1\n',
  'packages/commun/package.json': JSON.stringify({ name: '@m/commun', main: './dist/index.js' }),
  'packages/commun/tsconfig.json': '{\n  // commentaire\n  "extends": "./tsconfig.base.json",\n}\n',
  'packages/commun/tsconfig.base.json': '{ "compilerOptions": { "baseUrl": ".", "paths": { "#int/*": ["./src/interne/*"] } } }',
  'packages/commun/src/index.ts': "export { i } from '#int/i'\nexport const c = 2\n",
  'packages/commun/src/interne/i.ts': 'export const i = 3\n',
  'packages/ignore/package.json': JSON.stringify({ name: '@m/ignore' }),
  'svc/app/__init__.py': '',
  'svc/app/main.py': 'from app.core import x\n',
  'svc/app/core.py': 'x = 1\n',
  'scripts/outil.mjs': 'export const o = 1\n',
  'test/a.test.js': "import { m } from '../apps/web/src/main.js'\n",
}

test('workspaces : motifs `*`, `**`, exclusion `!` ; pnpm-workspace.yaml', () => {
  assert.ok(globRe('apps/*').test('apps/web'))
  assert.ok(!globRe('apps/*').test('apps/web/sous'))
  assert.ok(globRe('packages/**').test('packages/a/b'))
  assert.ok(globRe('**/pkg').test('x/y/pkg'))
  assert.deepEqual(pnpmPatterns("packages:\n  - 'packages/*'\n  - \"apps/*\" # commentaire\n  - '!**/test'\nautre:\n  - x\n"), ['packages/*', 'apps/*', '!**/test'])
  const cfg = load(project(MONOREPO))
  assert.deepEqual(cfg.discovery.workspaces.map((w) => [w.name, w.path, w.origine]), [['@m/web', 'apps/web', 'observé'], ['@m/commun', 'packages/commun', 'observé']])
  assert.equal(cfg.packages['@m/commun'], 'packages/commun/src', 'résolu depuis le dossier de son point d’entrée (dist/index.js → src/)')
})

test('alias : tsconfig (JSONC, extends, baseUrl) et vite.config lu sans exécution', () => {
  assert.equal(stripJsonComments('{ "a": "http://x", // c\n /* d */ "b": [1,], }'), '{ "a": "http://x", \n  "b": [1] }')
  const cfg = load(project(MONOREPO))
  const byAlias = Object.fromEntries(cfg.discovery.aliases.map((a) => [a.alias, a]))
  assert.equal(byAlias['@'].path, 'apps/web/src')
  assert.equal(byAlias['@'].confiance, 0.7)
  assert.match(byAlias['@'].indices[0], /lu sans exécuter/)
  assert.equal(byAlias['~lib'].path, 'apps/web/lib')
  assert.equal(byAlias['#int'].path, 'packages/commun/src/interne')
  assert.equal(byAlias['#int'].origine, 'observé')
  assert.deepEqual(aliasEntries("[{ find: '@', replacement: '/src' }, { find: 'x', replacement: resolve(__dirname, 'x') }]").map((e) => e.key), ['@', 'x'])
  assert.deepEqual(viteAliases('web/vite.config.ts', "alias: [{ find: '@', replacement: '/src' }]").map((a) => a.path), ['web/src'])
  assert.deepEqual(viteAliases('vite.config.js', 'alias: { "@": calcule() }'), [], 'forme non littérale : ignorée')
  assert.deepEqual(tsconfigAliases(project({ 'tsconfig.json': '{ "compilerOptions": { "paths": { "*": ["x/*"] } } }' }), 'tsconfig.json'), [])
})

test('racines Python : manifeste, disposition src/, paquet de premier niveau', () => {
  const r = discoverPythonRoots(['a/pyproject.toml', 'a/src/pk/__init__.py', 'b/app/__init__.py', 'b/app/sub/__init__.py', 'c/setup.py'])
  assert.deepEqual(r.map((x) => [x.path, x.origine]), [['a/src', 'observé'], ['b', 'inféré'], ['c', 'observé']])
  assert.deepEqual(load(project(MONOREPO)).pythonRoots, ['svc'])
})

test('points d’entrée : manifeste, scripts, index.html, sortie de build ramenée à la source', () => {
  assert.deepEqual(manifestTargets({ bin: { x: 'bin/x.js' }, main: 'i.js', exports: { '.': { import: './e.mjs' }, './p': './p.js' } }).map((t) => t.field), ['bin.x', 'main', 'exports[.][import]', 'exports[./p]'])
  assert.deepEqual(sourceOf('pk/dist/index.js'), { path: 'pk/src/index', mapped: true })
  assert.deepEqual(sourceOf('pk/main.ts'), { path: 'pk/main.ts', mapped: false })
  assert.equal(sourceOf('pk/types.d.ts'), null)
  assert.deepEqual(scriptFiles('tsc && node --max-old-space-size=4096 tools/a.mjs x; python -m x; py -3 s/b.py'), ['tools/a.mjs', 's/b.py'])
  assert.deepEqual(htmlScripts('<script type="module" src="/src/main.ts"></script>', 'web'), ['web/src/main.ts'])
  const cfg = load(project(MONOREPO))
  assert.ok(cfg.entries.includes('^apps/web/src/main\\.js$'))
  assert.ok(cfg.entries.includes('^scripts/outil\\.mjs$'))
  assert.ok(cfg.entries.some((e) => new RegExp(e).test('packages/commun/src/index.ts')))
})

test('code généré : marque en tête de commentaire seulement ; écarté de la liste et noté', () => {
  assert.equal(markIn('// @generated by protoc'), '@generated')
  assert.equal(markIn('/* eslint-disable */\n// Code generated by x. DO NOT EDIT.'), 'Code generated by x. DO NOT EDIT')
  assert.equal(markIn('// LE CODE GÉNÉRÉ : « auto-generated » se reconnaît'), null, 'un commentaire qui en parle')
  assert.equal(markIn('const x = 1 // auto-generated'), null)
  const cfg = load(project(MONOREPO))
  const rels = listCode(cfg).map((f) => f.rel)
  assert.ok(!rels.includes('apps/web/src/gen/types.js'))
  assert.deepEqual(cfg.discovery.generated.map((g) => [g.path, g.origine]), [['apps/web/src/gen/types.js', 'observé']])
})

test('groupes : workspaces observés, dossiers inférés, pas de groupe fait de tests seuls ; imports résolus', () => {
  const cfg = load(project(MONOREPO))
  const { groups } = resolveGroups(cfg, listCode(cfg))
  assert.deepEqual(groups.map((g) => [g.name, g.path, g.origine]), [['web', 'apps/web', 'observé'], ['commun', 'packages/commun', 'observé'], ['scripts', 'scripts', 'inféré'], ['svc', 'svc', 'inféré']])
  const { result } = collect(cfg, { hotspots: false })
  assert.deepEqual(result.coupling.unresolved, [])
  assert.deepEqual(result.coupling.orphans, [])
  const doc = JSON.parse(JSON.stringify(metricsDocument(result, null)))
  assert.deepEqual(validate(loadSchema('metrics.schema.json'), doc), [], 'nouveaux champs facultatifs : toujours v1')
  assert.equal(doc.coupling.resolution.aliases.find((a) => a.alias === '@').files, undefined)
  assert.equal(doc.coupling.resolution.entries.find((e) => e.pattern === '^scripts/outil\\.mjs$').files, 1)
})

test('la déclaration l’emporte ; `discover: false` coupe la découverte', () => {
  const root = project({
    ...MONOREPO,
    'archimetrics.config.json': JSON.stringify({ aliases: { '@': 'ailleurs' }, pythonRoots: ['svc/app'], entries: ['^x/'], groups: [{ name: 'tout', path: '.' }] }),
  })
  const cfg = load(root)
  const at = cfg.discovery.aliases.find((a) => a.alias === '@')
  assert.deepEqual([at.path, at.origine, at.confiance], ['ailleurs', 'déclaré', 1])
  assert.match(at.indices[1], /découvert autrement : apps\/web\/src/)
  assert.equal(cfg.aliases['~lib'], 'apps/web/lib', 'un alias découvert non déclaré reste')
  assert.deepEqual(cfg.pythonRoots, ['svc/app'])
  assert.equal(cfg.entries[0], '^x/')
  assert.deepEqual(resolveGroups(cfg, listCode(cfg)).groups.map((g) => [g.name, g.origine]), [['tout', 'déclaré']])
  const off = load(project({ ...MONOREPO, 'archimetrics.config.json': '{ "discover": false }' }))
  assert.deepEqual([off.aliases, off.pythonRoots, off.entries, off.discovery.generated], [{}, [], [], []])
  assert.equal(off.packages['@m/commun'], 'packages/commun', 'les workspaces restent détectés')
})

test('D-020 : avertissement quand les deux configurations diffèrent', () => {
  assert.deepEqual(configDifference({ limits: { a: 1, b: 2 }, name: 'x' }, { name: 'x', limits: { b: 2, a: 1 } }), [])
  assert.deepEqual(configDifference({ limits: { a: 1 } }, { limits: { a: 2 }, aliases: {} }), ['aliases', 'limits'])
  assert.equal(configWarning({ label: 'a', config: null }, { label: 'b', config: null }), null)
  assert.match(configWarning({ label: 'v1', config: { limits: { a: 1 } } }, { label: 'arbre', config: { limits: { a: 2 } } }), /clés différentes : limits.*--config.*D-020/)
  assert.match(configWarning({ label: 'v1', config: null }, { label: 'arbre', config: { name: 'x' } }), /absente côté v1/)
})
