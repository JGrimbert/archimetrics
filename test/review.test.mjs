const git = (cwd, ...args) => execFileSync('git', ['-c', 'user.name=t', '-c', 'user.email=t@t', '-c', 'commit.gpgsign=false', '-c', 'core.autocrlf=false', ...args], { cwd, encoding: 'utf8' })

/** Un dépôt factice : un commit de base, puis un commit qui touche `src/b.mjs` (importé par `src/a.mjs`). */
function fakeRepo() {
  const root = join(OUT, 'depot')
  mkdirSync(join(root, 'src'), { recursive: true })
  git(OUT, 'init', '-q', '-b', 'main', root)
  writeFileSync(join(root, 'package.json'), '{ "name": "factice", "type": "module" }\n')
  writeFileSync(join(root, 'src/a.mjs'), "import { b } from './b.mjs'\nexport const a = () => b(1)\n")
  writeFileSync(join(root, 'src/b.mjs'), 'export function b(x) {\n  return x + 1\n}\n')
  git(root, 'add', '.')
  git(root, 'commit', '-q', '-m', 'base')
  writeFileSync(join(root, 'src/b.mjs'), 'export function b(x) {\n  return x - 1\n}\n')
  writeFileSync(join(root, 'logo.png'), Buffer.from([0x89, 0x50, 0x4e, 0x47, 0, 1, 2, 3, 0]))
  git(root, 'add', '.')
  git(root, 'commit', '-q', '-m', 'b : le signe change')
  return root
}

test('dépôt : collecte (message, fichiers, diff, voisins, métriques avant/après), binaire exclu, lecture seule ; CLI LLM éteint', async () => {
  const root = fakeRepo()
  const status = git(root, 'status', '--porcelain')
  const seen = []
  const stop = onGit((args) => seen.push(args[0]))
  const doc = await reviewRepo({ root, range: 'HEAD', onGit: (args) => seen.push(args[0]) })
  stop()
  valid(doc)
  assert.equal(doc.changement.message, 'b : le signe change')
  assert.equal(doc.changement.depot, 'depot')
  assert.deepEqual(doc.collecte.fichiers.map((f) => [f.path, f.statut, f.exclu?.raison ?? null]), [['logo.png', 'ajouté', 'binaire'], ['src/b.mjs', 'modifié', null]])
  const ctx = doc.collecte.contexte
  assert.equal(ctx.disponible, true)
  assert.deepEqual(ctx.fichiers['src/b.mjs'], { importeurs: ['src/a.mjs'], imports: [], lignesAvant: 3, lignesApres: 3 })
  assert.equal(ctx.resume.files.apres, 2)
  assert.equal(doc.llm.statut, 'éteint')
  for (const c of new Set(seen)) assert.ok([...REVIEW_READ_ONLY, 'archive'].includes(c), `commande git inattendue : ${c}`)
  assert.equal(git(root, 'status', '--porcelain'), status, 'dépôt inchangé')

  const out = join(OUT, 'sortie')
  let printed = ''
  assert.equal(await runReview(['HEAD~1..HEAD', '--root', root, '--no-llm', '--out', out], { print: (s) => { printed += s } }), 0)
  const written = JSON.parse(readFileSync(join(out, 'review.json'), 'utf8'))
  valid(written)
  assert.equal(written.changement.label, 'HEAD~1..HEAD')
  assert.match(readFileSync(join(out, 'review.md'), 'utf8'), /Conclusion : rien de significatif/)
  assert.match(printed, /Revue écrite dans/)
  assert.equal(git(root, 'status', '--porcelain'), status, 'dépôt inchangé')
})

