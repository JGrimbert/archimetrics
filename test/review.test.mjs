test('contexte : voisins par le graphe, violations touchées (nouvelle, existante, résorbée)', () => {
  const edges = [{ from: 'a', to: 'b' }, { from: 'c', to: 'b' }, { from: 'b', to: 'd' }]
  assert.deepEqual(neighboursOf('b', edges), { importeurs: ['a', 'c'], imports: ['d'] })
  const v = touchedViolations(
    { cyclomatic: [{ key: 'src/b.mjs#f', value: 20, limit: 15 }, { key: 'src/b.mjs#g', value: 18, limit: 15 }] },
    { cyclomatic: [{ key: 'src/b.mjs#f', value: 21, limit: 15 }, { key: 'src/b.mjs#h', value: 16, limit: 15 }, { key: 'src/z.mjs#k', value: 30, limit: 15 }] },
    ['src/b.mjs'],
  )
  assert.deepEqual(v.map((x) => [x.cle, x.etat]), [['src/b.mjs#f', 'existante'], ['src/b.mjs#h', 'nouvelle'], ['src/b.mjs#g', 'résorbée']])
})

