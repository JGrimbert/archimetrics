test('« rien de significatif » : examen vide, preuve hors des lignes changées, ou contre-vérification non confirmée', async () => {
  const empty = await reviewChange({ diffText: DIFF, provider: fakeProvider() })
  valid(empty)
  assert.equal(empty.conclusion, 'rien de significatif')
  assert.equal(empty.llm.statut, 'actif')
  assert.equal(empty.llm.appels, 1)

  const offDiff = await reviewChange({ diffText: DIFF, provider: fakeProvider({ examen: () => ({ constats: [constat(' export function f(x) {')] }) }) })
  assert.equal(offDiff.conclusion, 'rien de significatif')
  assert.equal(offDiff.ecartes[0].raison, 'preuve absente des lignes changées')

  for (const verdict of ['réfuté', 'incertain']) {
    const p = fakeProvider({ examen: () => ({ constats: [constat('+  return x - 1')] }), verif: () => ({ justification: 'non', verdict }) })
    const doc = await reviewChange({ diffText: DIFF, provider: p })
    valid(doc)
    assert.equal(doc.conclusion, 'rien de significatif', verdict)
    assert.match(doc.ecartes[0].raison, new RegExp(verdict))
  }
  // Une seule vue qui confirme ne suffit pas.
  const half = fakeProvider({ examen: () => ({ constats: [constat('+  return x - 1')] }), verif: (m, n) => ({ justification: '…', verdict: n === 1 ? 'confirmé' : 'réfuté' }) })
  assert.equal((await reviewChange({ diffText: DIFF, provider: half })).conclusion, 'rien de significatif')
})

test('constat du LLM gardé : preuve retrouvée (même recopiée sur plusieurs lignes), fichier:ligne, deux vues confirmées', async () => {
  const p = fakeProvider({ examen: () => ({ constats: [constat('-  return x + 1\n+  return x - 1'), constat('+return x - 1', { nature: 'suggestion', description: 'nommer x' })] }) })
  const doc = await reviewChange({ diffText: DIFF, provider: p, label: 'HEAD' })
  valid(doc)
  assert.equal(doc.conclusion, 'constats')
  const [c, s] = doc.constats
  assert.deepEqual([c.source, c.fichier, c.ligne, c.preuve, c.nature], ['llm', 'src/a.mjs', 2, '+return x - 1', 'avéré'])
  assert.match(c.verification, /avant-après : confirmé.*diff : confirmé/)
  assert.equal(s.nature, 'suggestion')
  assert.equal(p.calls.filter((x) => x.schema === VERIF_SCHEMA).length, VIEWS.length, 'les suggestions ne sont pas contre-vérifiées')
  const views = p.calls.filter((x) => x.schema === VERIF_SCHEMA).map((x) => x.messages[1].content)
  assert.match(views[0], /AVANT le changement :\n```\nexport function f\(x\) \{\n  return x \+ 1/)
  assert.match(views[1], /Diff unifié/)
  assert.equal(locateProof('return x + 1', parseDiff(DIFF)[0].hunks).kind, '-')
  assert.equal(locateProof('x', parseDiff(DIFF)[0].hunks), null, 'une preuve trop courte n’est pas cherchée dans les lignes')
  assert.deepEqual(validate(EXAMEN_SCHEMA, { constats: [] }), [])
  assertSupported(EXAMEN_SCHEMA)
  assertSupported(VERIF_SCHEMA)
  assertSupported(SCHEMA)
})

