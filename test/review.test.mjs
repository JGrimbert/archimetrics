test('banc en mode « revue » : même cas et mêmes diffs, empreinte propre ; une revue notée comme au mode brut', async () => {
  const repos = { scribe: join(OUT, 'scribe-absent') }
  const brut = loadBench(BENCH_DIR, { repos })
  const revue = loadBench(BENCH_DIR, { repos, prompt: REVIEW_PROMPT })
  assert.notEqual(brut.empreinte, revue.empreinte)
  assert.deepEqual(revue.cas.map((c) => c.diffText), brut.cas.map((c) => c.diffText))
  const cas = { id: 'x', depot: 'archimetrics', attendu: 'défaut', constats: [{ motsCles: ['signe'] }], diffText: DIFF }
  const res = await reviewCase(fakeProvider({ examen: () => ({ constats: [constat('+  return x - 1', { description: 'le signe est inversé' })] }) }), cas, brut.depots, 2)
  const s = scoreCase(cas, res)
  assert.deepEqual([s.formatPremier, s.trouves, s.faux], [true, 1, 0])
  const off = await reviewCase(providerFrom({ provider: 'ollama', model: 'm' }, { fetch: async () => { throw new Error('ECONNREFUSED') } }), cas, brut.depots, 2)
  assert.equal(scoreCase(cas, off).formatFinal, false)
})
